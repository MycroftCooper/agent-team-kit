function stripBom(text) {
  return text.charCodeAt(0) === 0xfeff ? text.slice(1) : text;
}

function labelsFor(language) {
  const value = String(language || "en");
  if (LABELS[value]) return LABELS[value];
  if (LANGUAGE_ALIASES[value.toLowerCase()] || value.toLowerCase().startsWith("zh")) return ZH;
  return EN;
}

function localIso(date = new Date()) {
  const offsetMinutes = -date.getTimezoneOffset();
  const sign = offsetMinutes >= 0 ? "+" : "-";
  const abs = Math.abs(offsetMinutes);
  const pad = (value, width = 2) => String(value).padStart(width, "0");
  const offset = `${sign}${pad(Math.floor(abs / 60))}:${pad(abs % 60)}`;
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}T${pad(date.getHours())}:${pad(
    date.getMinutes(),
  )}:${pad(date.getSeconds())}${offset}`;
}

function inside(root, file) {
  const relative = path.relative(path.resolve(root), path.resolve(file));
  return relative === "" || (!relative.startsWith("..") && !path.isAbsolute(relative));
}

function assertInside(config, file, purpose) {
  if (!inside(config.workspace, file)) {
    throw new PluginError(`${purpose} resolves outside the plugin workspace (${file}); refusing to use it.`);
  }
  return file;
}

/**
 * Resolve the effective plugin configuration. Explicit DSH plugin config wins;
 * anything missing falls back to `<workspace>/agent-flow.config.json`, so any
 * project scaffolded by `atk init` works without extra configuration.
 *
 * @param {object} [config] DSH plugin config (workspace/flowDir/artifactDir/language).
 * @returns {object} Resolved config with absolute file paths and labels.
 */
export function resolveConfig(config = {}) {
  const workspace = path.resolve(config.workspace || DEFAULT_WORKSPACE || process.cwd());
  let projectDoc = null;
  try {
    projectDoc = JSON.parse(stripBom(readFileSync(path.join(workspace, "agent-flow.config.json"), "utf8")));
  } catch {
    projectDoc = null;
  }
  const layout = (projectDoc && projectDoc.layout) || {};
  const declared = (projectDoc && projectDoc.paths) || {};
  const flowDir = path.resolve(workspace, String(config.flowDir || layout.flowDir || DEFAULT_FLOW_DIR || ".agent-flow"));
  const artifactDir = path.resolve(
    workspace,
    String(config.artifactDir || layout.artifactDir || DEFAULT_ARTIFACT_DIR || "artifacts/agent-flow"),
  );
  const language = String(config.language || (projectDoc && projectDoc.language) || DEFAULT_LANGUAGE || "en");
  const flowRel = path.relative(workspace, flowDir);
  const flowBase = flowRel === "" || flowRel === "." ? "" : flowRel;
  const resolveFile = (declaredValue, fallbackName) => path.resolve(workspace, String(declaredValue || path.join(flowBase, fallbackName)));
  return {
    workspace,
    flowDir,
    artifactDir,
    language,
    labels: labelsFor(language),
    title: (projectDoc && projectDoc.board && projectDoc.board.title) || PLUGIN_TITLE,
    project: (projectDoc && projectDoc.project) || path.basename(workspace),
    files: {
      state: resolveFile(declared.state, "state.json"),
      runtime: resolveFile(declared.runtime, "runtime.json"),
      humanTodos: resolveFile(declared.humanTodos, "human-todos.json"),
      metrics: path.resolve(artifactDir, "metrics.jsonl"),
    },
  };
}

async function readJson(file, fallback) {
  try {
    return JSON.parse(stripBom(await fsp.readFile(file, "utf8")));
  } catch {
    return fallback;
  }
}

async function readMetrics(file) {
  try {
    const text = await fsp.readFile(file, "utf8");
    const rows = stripBom(text)
      .split(/\r?\n/)
      .filter(Boolean)
      .map((line) => JSON.parse(line));
    let tokens = 0;
    let readLines = 0;
    for (const row of rows) {
      tokens += Number(row && row.tokens) || 0;
      readLines += Number(row && row.readLines) || 0;
    }
    return { samples: rows.length, tokens, readLines, lastAt: rows.length ? rows[rows.length - 1].at || null : null };
  } catch {
    return { samples: 0, tokens: 0, readLines: 0, lastAt: null };
  }
}

function evidenceCount(value) {
  if (Array.isArray(value)) return value.length;
  if (typeof value === "string") return value.trim() === "" ? 0 : 1;
  return 0;
}

function packageView(pkg) {
  return {
    id: pkg.id,
    type: pkg.type || null,
    typeRaw: pkg.typeRaw || null,
    owner: pkg.owner || null,
    priority: pkg.priority || null,
    stage: pkg.stage || "proposed",
    module: pkg.module || null,
    scope: pkg.scope || null,
    statusRaw: pkg.statusRaw || null,
    note: pkg.note || "",
    evidence: evidenceCount(pkg.evidence),
    deps: Array.isArray(pkg.deps) ? pkg.deps.slice() : [],
  };
}

function compareId(a, b) {
  return String(a.id || "").localeCompare(String(b.id || ""), "en", { numeric: true });
}

/**
 * Build the board snapshot. `state.json` is required; missing runtime/todos or
 * metrics degrade to empty collections. Throws PluginError when state is absent.
 *
 * @param {object} [pluginConfig] Raw DSH plugin config.
 * @returns {Promise<object>} JSON-serialisable snapshot.
 */
export async function buildSnapshot(pluginConfig = {}) {
  const config = pluginConfig && pluginConfig.files ? pluginConfig : resolveConfig(pluginConfig);
  const stateFile = assertInside(config, config.files.state, "state file");
  const state = await readJson(stateFile, undefined);
  if (!state || typeof state !== "object" || Array.isArray(state)) {
    throw new PluginError(
      `State file not found: ${stateFile}. Run \`atk init\` / \`atk state import\` in ${config.workspace}, ` +
        "or install the plugin with flowDir/artifactDir from agent-flow.config.json.",
    );
  }
  const runtime = (await readJson(assertInside(config, config.files.runtime, "runtime file"), null)) || {};
  const todos = (await readJson(assertInside(config, config.files.humanTodos, "human-todos file"), null)) || { items: [] };
  const metrics = await readMetrics(assertInside(config, config.files.metrics, "metrics file"));

  const packages = Array.isArray(state.packages) ? state.packages : [];
  const byStage = Object.fromEntries(STAGE_ORDER.map((stage) => [stage, 0]));
  const moduleCounts = new Map();
  const active = [];
  const archived = [];
  for (const pkg of packages) {
    if (!pkg || typeof pkg !== "object") continue;
    const stage = pkg.stage || "proposed";
    byStage[stage] = (byStage[stage] || 0) + 1;
    if (pkg.archived) {
      archived.push({
        id: pkg.id,
        type: pkg.type || null,
        typeRaw: pkg.typeRaw || null,
        owner: pkg.owner || null,
        module: pkg.module || null,
        note: pkg.note || "",
        archivedAt: pkg.archivedAt || null,
        archiveReason: pkg.archiveReason || null,
        archiveEvidence: pkg.archiveEvidence || null,
      });
      continue;
    }
    active.push(packageView(pkg));
    if (pkg.module) moduleCounts.set(pkg.module, (moduleCounts.get(pkg.module) || 0) + 1);
  }
  active.sort(compareId);
  archived.sort(compareId);
  const modules = [...moduleCounts.entries()]
    .map(([moduleName, total]) => ({ name: moduleName, total }))
    .sort((a, b) => String(a.name).localeCompare(String(b.name), "en"));
  const batch = state.batch && typeof state.batch === "object" ? state.batch : null;
  const slices = Array.isArray(batch && batch.slices) ? batch.slices : [];
  const agents = (Array.isArray(runtime.agents) ? runtime.agents.slice() : []).sort((a, b) =>
    String((a && a.role) || "").localeCompare(String((b && b.role) || ""), "en"),
  );

  return {
    generatedAt: localIso(new Date()),
    title: config.title,
    project: config.project,
    language: config.language,
    labels: config.labels,
    plugin: { id: name, package: PACKAGE_NAME, route: ROUTE, title: PLUGIN_TITLE },
    batch,
    counts: { total: packages.length, byStage, modules },
    packages: active,
    archived,
    humanTodos: Array.isArray(todos.items) ? todos.items : [],
    agents,
    milestones: slices,
    events: Array.isArray(runtime.events) ? runtime.events : [],
    metrics,
    updatedAt: state.updatedAt || null,
    runtimeUpdatedAt: runtime.updatedAt || null,
  };
}

/** The single write this plugin performs: flip a human-only todo. */
export async function toggleHumanTodo(pluginConfig, id) {
  const config = pluginConfig && pluginConfig.files ? pluginConfig : resolveConfig(pluginConfig);
  const file = assertInside(config, config.files.humanTodos, "human-todos file");
  if (typeof id !== "string" || id.trim() === "") return { ok: false, reason: "missing todo id" };
  const doc = (await readJson(file, null)) || { schemaVersion: 1, items: [] };
  if (!Array.isArray(doc.items)) doc.items = [];
  const item = doc.items.find((entry) => String(entry.id || "").toUpperCase() === id.trim().toUpperCase());
  if (!item) return { ok: false, reason: `unknown todo id "${id}"` };
  item.done = !item.done;
  item.doneAt = item.done ? new Date().toISOString() : null;
  doc.updatedAt = new Date().toISOString();
  const text = `${JSON.stringify(doc, null, 2)}\n`;
  const tmp = `${file}.tmp-${process.pid}-${Date.now()}`;
  await fsp.writeFile(tmp, text, "utf8");
  await fsp.rename(tmp, file);
  return { ok: true, item };
}

