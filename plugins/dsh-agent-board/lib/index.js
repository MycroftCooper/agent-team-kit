function sendJson(response, statusCode, payload, extraHeaders) {
  const body = JSON.stringify(payload);
  response.writeHead(statusCode, {
    "content-type": "application/json; charset=utf-8",
    "cache-control": "no-store",
    "content-length": Buffer.byteLength(body, "utf8"),
    ...(extraHeaders || {}),
  });
  response.end(body);
}

function sendText(response, statusCode, text, extraHeaders) {
  response.writeHead(statusCode, {
    "content-type": "text/plain; charset=utf-8",
    "cache-control": "no-store",
    ...(extraHeaders || {}),
  });
  response.end(text);
}

function readBody(request) {
  return new Promise((resolve) => {
    let raw = "";
    let overflow = false;
    request.on("data", (chunk) => {
      if (overflow) return;
      raw += chunk;
      if (raw.length > MAX_POST_BODY) {
        overflow = true;
        raw = "";
      }
    });
    request.on("end", () => resolve({ raw, overflow }));
    request.on("error", () => resolve({ raw: "", overflow: false }));
  });
}

async function fileSignature(files) {
  const parts = [];
  for (const file of files) {
    try {
      const info = await fsp.stat(file);
      parts.push(`${file}:${info.mtimeMs}:${info.size}`);
    } catch {
      parts.push(`${file}:-`);
    }
  }
  return parts.join("|");
}

/**
 * Build the HTTP handler and its cleanup function. Exported for the standalone
 * selftest; normally created through apply().
 */
export function createHandler(pluginConfig = {}) {
  const config = resolveConfig(pluginConfig);
  const clients = new Set();
  const watchers = [];
  const files = [config.files.state, config.files.runtime, config.files.humanTodos, config.files.metrics];
  let debounce = null;
  let lastSignature = "";
  let closed = false;

  const broadcast = () => {
    for (const client of clients) {
      try {
        client.write("data: changed\n\n");
      } catch {
        clients.delete(client);
      }
    }
  };

  const schedule = () => {
    if (closed) return;
    clearTimeout(debounce);
    debounce = setTimeout(async () => {
      debounce = null;
      const signature = await fileSignature(files);
      // Re-arm after every change: the workflow writes files via temp+rename,
      // and a file watcher does not follow the replaced inode everywhere.
      await refreshWatchers();
      if (signature === lastSignature) return;
      lastSignature = signature;
      broadcast();
    }, 120);
    if (debounce.unref) debounce.unref();
  };

  // Watch the data files themselves: some Node/Windows builds abort on
  // directory fs.watch events, so directory watches are deliberately avoided.
  const refreshWatchers = async () => {
    if (closed) return;
    for (const watcher of watchers) {
      try {
        watcher.close();
      } catch {
        // already closed
      }
    }
    watchers.length = 0;
    for (const file of files) {
      try {
        const info = await fsp.stat(file);
        if (!info.isFile()) continue;
        const watcher = watch(file, { persistent: false }, schedule);
        watcher.on("error", () => {});
        watchers.push(watcher);
      } catch {
        // Missing file; another watched file or the page fallback poll recovers.
      }
    }
  };

  const attach = async () => {
    lastSignature = await fileSignature(files);
    await refreshWatchers();
  };

  const handler = async (request, response) => {
    try {
      const url = new URL(request.url || "/", "http://localhost");
      const pathname = url.pathname;
      const api = (suffix) => `${ROUTE}${suffix}`;
      const isGet = request.method === "GET" || request.method === "HEAD";

      if (pathname === api("/api/events")) {
        if (!isGet) {
          sendText(response, 405, "method not allowed", { allow: "GET, HEAD" });
          return;
        }
        response.writeHead(200, {
          "content-type": "text/event-stream; charset=utf-8",
          "cache-control": "no-store",
          connection: "keep-alive",
        });
        response.write(": connected\n\n");
        clients.add(response);
        request.on("close", () => clients.delete(response));
        return;
      }

      if (pathname === api("/api/human-todos/toggle")) {
        if (request.method !== "POST") {
          sendText(response, 405, "method not allowed", { allow: "POST" });
          return;
        }
        const { raw, overflow } = await readBody(request);
        if (overflow) {
          sendJson(response, 413, { ok: false, reason: "request body too large" });
          return;
        }
        let payload;
        try {
          payload = JSON.parse(raw || "{}");
        } catch {
          sendJson(response, 400, { ok: false, reason: "invalid JSON body" });
          return;
        }
        try {
          const result = await toggleHumanTodo(config, payload && payload.id);
          sendJson(response, result.ok ? 200 : 400, result);
        } catch (error) {
          sendJson(response, 500, { ok: false, reason: String((error && error.message) || error) });
        }
        return;
      }

      if (pathname === api("/api/snapshot")) {
        if (!isGet) {
          sendText(response, 405, "method not allowed", { allow: "GET, HEAD" });
          return;
        }
        try {
          sendJson(response, 200, await buildSnapshot(config));
        } catch (error) {
          const reason = String((error && error.message) || error);
          sendJson(response, error instanceof PluginError ? 503 : 500, { ok: false, error: reason });
        }
        return;
      }

      if (pathname === ROUTE || pathname === `${ROUTE}/`) {
        if (!isGet) {
          sendText(response, 405, "method not allowed", { allow: "GET, HEAD" });
          return;
        }
        const html = pageHtml(config);
        response.writeHead(200, {
          "content-type": "text/html; charset=utf-8",
          "cache-control": "no-store",
          "content-length": Buffer.byteLength(html, "utf8"),
        });
        response.end(html);
        return;
      }

      sendText(response, 404, "not found");
    } catch (error) {
      try {
        if (!response.headersSent) {
          sendJson(response, 500, { ok: false, error: String((error && error.message) || error) });
        } else {
          response.end();
        }
      } catch {
        // response already gone
      }
    }
  };

  const dispose = () => {
    if (closed) return;
    closed = true;
    clearTimeout(debounce);
    debounce = null;
    for (const watcher of watchers) {
      try {
        watcher.close();
      } catch {
        // already closed
      }
    }
    watchers.length = 0;
    for (const client of clients) {
      try {
        client.end();
      } catch {
        // already closed
      }
    }
    clients.clear();
  };

  return { handler, dispose, attach, config };
}

/**
 * cordis host plugin entry point. Registers a prefix route (so
 * `<route>/api/*` matches) plus the exact page route.
 */
export function apply(ctx, config = {}) {
  const board = createHandler(config);
  void board.attach();
  ctx.effect(() => {
    // The prefix route must not carry a trailing slash: the web server uses
    // `${prefix}/` as its boundary, so "/board/" would never match "/board/api/*".
    const disposePrefix = ctx.webServer.register({ kind: "prefix", path: ROUTE, handler: board.handler });
    const disposeExact = ctx.webServer.register({ kind: "exact", path: ROUTE, handler: board.handler });
    return () => {
      disposeExact();
      disposePrefix();
      board.dispose();
    };
  });
}
