export const LABELS = { en: EN, "zh-CN": ZH, zh: ZH };

export function getLabels(language = "en") {
  const labels = LABELS[language] ?? LABELS.en;
  return labels;
}

export function stageLabel(labels, stage) {
  return labels.stage[stage] ?? stage;
}

export function sliceLabel(labels, status) {
  return labels.slice[status] ?? status;
}

export function typeLabel(labels, type) {
  return labels.type[type] ?? type;
}
